export const LANGS = ['sv', 'en'] as const;
export type Lang = (typeof LANGS)[number];

export function isLang(value: string | undefined): value is Lang {
  return value === 'sv' || value === 'en';
}

/** The preferred language from an Accept-Language header; Swedish unless English ranks higher. */
export function preferredLang(acceptLanguage: string | undefined): Lang {
  for (const part of (acceptLanguage ?? '').split(',')) {
    const tag = part.trim().slice(0, 2).toLowerCase();
    if (tag === 'sv' || tag === 'en') return tag;
  }
  return 'sv';
}

